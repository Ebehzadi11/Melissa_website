/**
 * Portfolio gallery generator.
 *
 * Scans public/media/portfolio/ for images, reads each one's real pixel
 * dimensions, merges optional captions.json, and writes a typed list to
 * src/content/portfolio-images.ts.
 *
 * Usage:  npm run portfolio
 *
 * To add photos: drop image files into public/media/portfolio/ (any name;
 * they display in filename order — 01.jpg, 02.jpg, ...), then run the command.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(fileURLToPath(import.meta.url), "../..");
const DIR = path.join(ROOT, "public/media/portfolio");
const OUT = path.join(ROOT, "src/content/portfolio-images.ts");
const CAPTIONS = path.join(DIR, "captions.json");

const IMAGE_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

/** Read pixel dimensions of an image (macOS `sips`, with a PNG/JPEG fallback). */
function dimensions(file) {
  try {
    const out = execFileSync("sips", ["-g", "pixelWidth", "-g", "pixelHeight", file], {
      encoding: "utf8",
    });
    const w = /pixelWidth:\s*(\d+)/.exec(out)?.[1];
    const h = /pixelHeight:\s*(\d+)/.exec(out)?.[1];
    if (w && h) return { width: Number(w), height: Number(h) };
  } catch {
    /* sips not available — fall through */
  }
  return { width: 900, height: 1200 }; // safe portrait default
}

function main() {
  if (!fs.existsSync(DIR)) {
    console.error(`Folder not found: ${DIR}`);
    process.exit(1);
  }

  const captions = fs.existsSync(CAPTIONS)
    ? JSON.parse(fs.readFileSync(CAPTIONS, "utf8"))
    : {};

  const files = fs
    .readdirSync(DIR)
    .filter((f) => IMAGE_EXT.has(path.extname(f).toLowerCase()))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

  if (files.length === 0) {
    console.error(`No images found in ${DIR}`);
    process.exit(1);
  }

  const items = files.map((file) => {
    const { width, height } = dimensions(path.join(DIR, file));
    const cap = captions[file] ?? {};
    const alt = cap.alt ?? {
      pt: `Melissa Oliveira — foto de portfólio`,
      en: `Melissa Oliveira — portfolio photo`,
    };
    return {
      src: `/media/portfolio/${file}`,
      width,
      height,
      alt,
      objectPosition: cap.objectPosition,
    };
  });

  const body = `// AUTO-GENERATED by scripts/gen-portfolio.mjs — do not edit by hand.
// To change photos: edit public/media/portfolio/ (+ captions.json), then run \`npm run portfolio\`.
import type { ImageAsset } from "./site";

export const portfolioImages: ImageAsset[] = ${JSON.stringify(items, null, 2)
    .replace(/"(\w+)":/g, "$1:")
    .replace(/objectPosition: undefined,?\n\s*/g, "")};
`;

  fs.writeFileSync(OUT, body);
  console.log(`✓ Wrote ${items.length} portfolio image(s) to src/content/portfolio-images.ts`);
  for (const it of items) {
    console.log(`   ${it.src.padEnd(34)} ${it.width}×${it.height}`);
  }
}

main();
